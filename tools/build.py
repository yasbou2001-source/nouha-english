"""Build data/content.js from content/*.json (lessons + placement test).

Usage: python tools/build.py
The site loads data/content.js with a plain <script> tag, so it works from file://.
"""
import glob
import json
import os
import sys
import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import validate  # noqa: E402


def main():
    v = validate.V()
    lessons = []
    files = sorted(glob.glob(os.path.join(ROOT, "content", "lessons_*.json")))
    if not files:
        print("No content/lessons_*.json files found")
        return 1
    for fn in files:
        lessons.extend(validate.validate_file(fn, v))
    if v.errors:
        for e in v.errors:
            print("ERROR", e)
        print(f"\nBuild aborted: {len(v.errors)} error(s).")
        return 1
    ids = [L["id"] for L in lessons]
    if len(ids) != len(set(ids)):
        print("ERROR duplicate lesson ids:", [i for i in ids if ids.count(i) > 1])
        return 1
    lessons.sort(key=lambda L: L["order"])

    placement = []
    pfile = os.path.join(ROOT, "content", "placement.json")
    if os.path.exists(pfile):
        with open(pfile, encoding="utf-8") as f:
            placement = json.load(f)

    content = {
        "built": datetime.datetime.now().isoformat(timespec="seconds"),
        "lessons": lessons,
        "placement": placement,
    }
    js = json.dumps(content, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
    out = os.path.join(ROOT, "data", "content.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build.py — do not edit by hand. Edit content/*.json then rebuild.\n")
        f.write("window.NOUHA_CONTENT = " + js + ";\n")

    n_ex = sum(len(L["exercises"]) for L in lessons)
    n_vocab = sum(len(s["items"]) for L in lessons for s in L["sections"] if s["type"] == "vocab")
    print(f"Built {out}")
    print(f"  lessons: {len(lessons)} ({', '.join(ids)})")
    print(f"  exercises: {n_ex}, vocab items: {n_vocab}, placement questions: {len(placement)}")
    print(f"  size: {os.path.getsize(out)//1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
